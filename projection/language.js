function initialLanguage() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q === "zh" || q === "en") return q;
  if (window.entryLanguage) return window.entryLanguage;
  try {
    if (localStorage.getItem("verb-language") === "en") return "en";
  } catch {}
  return "zh";
}
